#!/bin/sh
# Regenerate configs/streamdeck_*_defconfig from Buildroot's upstream Raspberry
# Pi defconfigs plus our additions. Run after bumping the Buildroot version:
#   scripts/gen-defconfigs.sh /path/to/buildroot
set -eu
BR="$1"
HERE="$(cd "$(dirname "$0")/.." && pwd)"
EXT='$(BR2_EXTERNAL_STREAMDECK_OS_PATH)'

gen() { # gen <upstream defconfig> <our name>
	up="$BR/configs/$1"
	out="$HERE/configs/$2"
	post_build=$(sed -n 's/^BR2_ROOTFS_POST_BUILD_SCRIPT="\(.*\)"/\1/p' "$up")
	post_image=$(sed -n 's/^BR2_ROOTFS_POST_IMAGE_SCRIPT="\(.*\)"/\1/p' "$up")
	frags=$(sed -n 's/^BR2_LINUX_KERNEL_CONFIG_FRAGMENT_FILES="\(.*\)"/\1/p' "$up")
	{
		echo "# Generated by scripts/gen-defconfigs.sh from Buildroot $(cat "$BR/.br-version" 2>/dev/null || git -C "$BR" describe --tags 2>/dev/null) configs/$1"
		grep -v -e '^BR2_ROOTFS_POST_BUILD_SCRIPT=' -e '^BR2_ROOTFS_POST_IMAGE_SCRIPT=' \
			-e '^BR2_LINUX_KERNEL_CONFIG_FRAGMENT_FILES=' -e '^BR2_TARGET_ROOTFS_EXT2_SIZE=' "$up"
		cat <<EOT

# ---- StreamDeck OS ----
BR2_TARGET_GENERIC_HOSTNAME="streamdeck"
BR2_TARGET_GENERIC_ISSUE="StreamDeck OS"
BR2_ROOTFS_DEVICE_CREATION_DYNAMIC_MDEV=y
BR2_ROOTFS_OVERLAY="$EXT/board/common/rootfs-overlay"
BR2_ROOTFS_POST_BUILD_SCRIPT="$post_build $EXT/board/common/post-build.sh"
BR2_ROOTFS_POST_IMAGE_SCRIPT="$EXT/board/common/rpi-bootfs.sh $post_image"
BR2_LINUX_KERNEL_CONFIG_FRAGMENT_FILES="${frags:+$frags }$EXT/board/common/linux.fragment"
BR2_TARGET_ROOTFS_EXT2_SIZE="160M"
BR2_PACKAGE_HOST_GO_BIN=y
BR2_PACKAGE_STREAMDECKD=y
BR2_PACKAGE_CA_CERTIFICATES=y
BR2_PACKAGE_CHRONY=y
BR2_PACKAGE_WPA_SUPPLICANT=y
BR2_PACKAGE_WPA_SUPPLICANT_NL80211=y
BR2_PACKAGE_BRCMFMAC_SDIO_FIRMWARE_RPI=y
BR2_PACKAGE_BRCMFMAC_SDIO_FIRMWARE_RPI_WIFI=y
EOT
	} > "$out"
	echo "wrote $out"
}

gen raspberrypi4_64_defconfig streamdeck_rpi4_defconfig
gen raspberrypi5_defconfig streamdeck_rpi5_defconfig
gen raspberrypi3_64_defconfig streamdeck_rpi3_defconfig
